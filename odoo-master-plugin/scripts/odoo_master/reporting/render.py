"""Render Markdown reports to standalone HTML and to real PDF.

PDF engines, tried in order (the first available wins; the result records which one ran):
  1. Node + Playwright Chromium (`page.pdf`, prints backgrounds; renders Mermaid when the mermaid
     script can be loaded from cdn.jsdelivr.net — otherwise diagrams stay as code blocks)
  2. Chrome/Chromium binary `--headless --print-to-pdf`
  3. ReportLab text layout (no HTML styling; tables flattened) — last resort
The output is verified: the PDF must start with %PDF and (when pypdf is installed) have >= 1 page.
"""
