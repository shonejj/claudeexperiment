def build_html(md_text: str, title: str | None = None) -> tuple[str, dict]:
    fm, body = split_frontmatter(md_text)
    body = redact_text(body)
    title = title or fm.get("title") or next((ln[2:].strip() for ln in body.splitlines() if ln.startswith("# ")), "Report")
    meta = " · ".join(f"{k}: {html.escape(str(fm[k]))}" for k in ("kind", "ticket", "execution", "odoo_version", "generated_at") if fm.get(k))
    content = to_html(body)
    has_mermaid = 'class="mermaid"' in content
    mermaid = ('<script src="https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.min.js"></script>'
               '<script>try{mermaid.initialize({startOnLoad:true,theme:"neutral"})}catch(e){}</script>') if has_mermaid else ""
    doc = f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)}</title><style>{CSS}</style>{mermaid}</head><body>
<header class="doc"><h1>{html.escape(title)}</h1><div class="meta">{meta}</div></header>
{content}
<footer class="doc">Generated by odoo-master · {now_iso()}</footer></body></html>"""
    return doc, {"title": title, "frontmatter": fm, "mermaid": has_mermaid}


def _pdf_playwright(html_path: Path, pdf_path: Path, mermaid: bool) -> tuple[bool, str]:
    node = shutil.which("node")
    script = PLUGIN_ROOT / "scripts" / "reporting" / "html_to_pdf.mjs"
    if not node or not script.exists():
        return False, "node or html_to_pdf.mjs missing"
    r = subprocess.run([node, str(script), str(html_path), str(pdf_path), "1" if mermaid else "0"], capture_output=True, text=True, timeout=180)
    return r.returncode == 0 and pdf_path.exists(), (r.stderr or r.stdout)[-400:]


def _pdf_chrome(html_path: Path, pdf_path: Path) -> tuple[bool, str]:
    for b in ("chromium", "chromium-browser", "google-chrome", "/opt/pw-browsers/chromium"):
        exe = shutil.which(b) or (b if Path(b).is_file() else None)
        if exe:
            r = subprocess.run([exe, "--headless", "--no-sandbox", "--disable-gpu", f"--print-to-pdf={pdf_path}",
                                "--no-pdf-header-footer", html_path.as_uri()], capture_output=True, text=True, timeout=120)
            if pdf_path.exists():
                return True, exe
            return False, r.stderr[-300:]
    return False, "no chrome binary"


def _pdf_reportlab(md_text: str, pdf_path: Path, title: str) -> tuple[bool, str]:
    try:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet
        from reportlab.platypus import Paragraph, Preformatted, SimpleDocTemplate, Spacer
    except ImportError:
        return False, "reportlab not installed"
    styles = getSampleStyleSheet()
    story = [Paragraph(html.escape(title), styles["Title"])]
    _, body = split_frontmatter(md_text)
    in_code, buf = False, []
    for ln in body.splitlines():
        if ln.strip().startswith("```"):
            if in_code:
                story.append(Preformatted("\n".join(buf), styles["Code"]))
                buf = []
            in_code = not in_code
            continue
        if in_code:
            buf.append(ln)
        elif ln.startswith("#"):
            lvl = min(len(ln) - len(ln.lstrip("#")), 3)
            story.append(Paragraph(html.escape(ln.lstrip("# ")), styles[f"Heading{lvl}"]))
        elif ln.strip():
            story.append(Paragraph(html.escape(ln), styles["BodyText"]))
        else:
            story.append(Spacer(1, 4))
    SimpleDocTemplate(str(pdf_path), pagesize=A4).build(story)
    return pdf_path.exists(), "reportlab"


def verify_pdf(path: Path) -> dict:
    if not path.exists():
        return {"ok": False, "error": "missing"}
    head = path.read_bytes()[:5]
    if head != b"%PDF-":
        return {"ok": False, "error": "not a PDF"}
    info = {"ok": True, "bytes": path.stat().st_size}
    try:
        from pypdf import PdfReader  # type: ignore
        info["pages"] = len(PdfReader(str(path)).pages)
        info["ok"] = info["pages"] >= 1
    except ImportError:
        info["pages"] = None
    except Exception as exc:  # noqa: BLE001
        info.update(ok=False, error=f"unreadable PDF: {exc}")
    return info


def render(src: Path, formats: list[str] | None = None, out_dir: Path | None = None, title: str | None = None,
           project_root: Path | None = None) -> dict:
    formats = formats or ["html", "pdf"]
    md_text = Path(src).read_text(encoding="utf-8")
    out_dir = Path(out_dir) if out_dir else Path(src).parent
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = Path(src).stem
    doc, meta = build_html(md_text, title)
    outputs = []
    html_path = out_dir / f"{stem}.html"
    html_path.write_text(doc, encoding="utf-8")
    if "html" in formats:
        outputs.append({"format": "html", "path": str(html_path), "ok": True})
    if "pdf" in formats:
        pdf = out_dir / f"{stem}.pdf"
        if pdf.exists():
            pdf.unlink()
        engine, detail = None, []
        for name, fn in (("playwright-chromium", lambda: _pdf_playwright(html_path, pdf, meta["mermaid"])),
                         ("chrome-cli", lambda: _pdf_chrome(html_path, pdf)),
                         ("reportlab", lambda: _pdf_reportlab(md_text, pdf, meta["title"]))):
            ok, msg = fn()
            detail.append({name: "ok" if ok else msg})
            if ok:
                engine = name
                break
        v = verify_pdf(pdf)
        outputs.append({"format": "pdf", "path": str(pdf), "engine": engine, "ok": bool(engine) and v["ok"], "verify": v,
                        "attempts": detail})
    if "html" not in formats:
        html_path.unlink(missing_ok=True)
    return {"source": str(src), "title": meta["title"], "rendered_at": now_iso(), "outputs": outputs,
            "frontmatter": json.loads(json.dumps(meta["frontmatter"], default=str))}
