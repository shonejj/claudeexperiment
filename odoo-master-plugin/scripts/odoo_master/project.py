"""Project analysis: builds the Odoo Master project knowledge model in .odoo-master/.

Files (owned by this tool; regenerated idempotently, never hand-edited):
  project-inventory.json, architecture-map.json, module-dependency-map.json, odoo-version.json,
  project-context.md
"""
from __future__ import annotations

from pathlib import Path

from .odoo import inventory as inv_mod
from .odoo import version as ver_mod
from .repository import environment, git_state
from .util import now_iso, state_dir, write_json


def analyze(root: Path | str, write: bool = True, include_core: bool = False) -> dict:
    root = Path(root).resolve()
    ver = ver_mod.detect(root)
    inv = inv_mod.scan(root, include_core=include_core, series=ver.get("version"))
    git = git_state(root)
    env = environment(root)
    knowledge_limits = [
        "Code-level analysis only: installed modules, real schema and data are NOT known until a database is inspected (odoo-master db overview).",
    ]
    if not inv["odoo_core_in_repo"]:
        knowledge_limits.append("Odoo core/Enterprise source is not in this repository: standard model definitions and extension points "
                                "cannot be traced locally (use the runtime image or an Odoo checkout).")
    if ver.get("conflicts"):
        knowledge_limits.append("Odoo version signals conflict — confirm the target version before making changes.")
    project = {
        "schema_version": 1,
        "generated_at": now_iso(),
        "root": str(root),
        "git": git,
        "environment": env,
        "odoo": {"version": ver.get("version"), "confidence": ver.get("confidence"), "conflicts": ver.get("conflicts"),
                 "addons_paths": inv["addons_paths"], "core_in_repo": inv["odoo_core_in_repo"],
                 "protected_core_paths": inv["protected_core_paths"],
                 "enterprise_dependencies": inv["dependencies"]["enterprise_dependencies"]},
        "summary": inv_mod.summary(inv),
        "knowledge_limits": knowledge_limits,
    }
    if write:
        sd = state_dir(root)
        write_json(sd / "project-inventory.json", {**project, "modules": inv["modules"], "findings": inv["findings"]})
        write_json(sd / "module-dependency-map.json", inv["dependencies"])
        write_json(sd / "architecture-map.json", inv["architecture"])
        write_json(sd / "odoo-version.json", ver)
        (sd / "project-context.md").write_text(render_context(project, inv, ver), encoding="utf-8")
    return {"project": project, "inventory": inv, "version": ver}


def render_context(project: dict, inv: dict, ver: dict) -> str:
    g = project["git"]
    lines = [
        "# Project context (generated by odoo-master — do not edit)",
        "",
        f"- Generated: {project['generated_at']}",
        f"- Root: `{project['root']}`",
        f"- Git: branch `{g.get('branch')}` @ `{g.get('head')}`, default `{g.get('default_branch')}`, dirty={g.get('dirty')}"
        if g.get("is_git") else "- Git: not a repository",
        f"- Odoo version: **{ver.get('version') or 'unknown'}** (confidence {ver.get('confidence')})",
    ]
    for s in ver.get("signals", [])[:6]:
        lines.append(f"  - {s['source']}: {s['version']} ← {s['evidence']}")
    if ver.get("conflicts"):
        lines.append(f"  - **Conflicts:** {len(ver['conflicts'])} — ask before proceeding")
    lines += ["", f"## Modules ({inv['module_count']})", "", "| Module | Version | Depends | Models | Views | Tests |", "|---|---|---|---|---|---|"]
    for n, m in sorted(inv["modules"].items()):
        mf = m.get("manifest") or {}
        lines.append(f"| {n} | {mf.get('version') or ''} | {', '.join(mf.get('depends') or [])} | {len(m['models'])} | {len(m['views'])} | "
                     f"{m['tests']['python'] + m['tests']['js']} |")
    lines += ["", "## Standard models extended", ""]
    ext = [(k, v) for k, v in inv["architecture"]["models"].items() if v["standard_model_extended"]]
    for k, v in sorted(ext)[:60]:
        std = f" (standard: `{v['standard_defined_in']}`)" if v.get("standard_defined_in") else " (not a known Community model — Enterprise/third-party?)"
        lines.append(f"- `{k}`{std} ← {', '.join(sorted(set(v['extended_in'])))}")
    f = inv["findings"]
    lines += ["", "## Findings", "",
              f"- Models without ACL: {len(f['models_missing_acl'])}",
              f"- Python syntax errors: {len(f['syntax_errors'])}; XML errors: {len(f['xml_errors'])}; manifest errors: {len(f['manifest_errors'])}",
              f"- Dependency cycles: {len(f['dependency_cycles'])}; unknown dependencies: {sum(len(v) for v in f['unknown_dependencies'].values())}",
              f"- Modules without tests: {', '.join(f['modules_without_tests']) or 'none'}",
              "", "## Knowledge limits", ""]
    lines += [f"- {k}" for k in project["knowledge_limits"]]
    return "\n".join(lines) + "\n"
